CREATE TABLE vouchers (
  id CHAR(36) NOT NULL PRIMARY KEY,
  booking_id VARCHAR(120) NOT NULL,
  booking_reference VARCHAR(120) NOT NULL,
  client VARCHAR(255) NOT NULL,
  member_id VARCHAR(120) NOT NULL,
  country VARCHAR(120) NOT NULL,
  property_name VARCHAR(255) NOT NULL,
  address TEXT NOT NULL,
  property_contact VARCHAR(120) NOT NULL,
  rooms INT NOT NULL,
  extra_beds INT NOT NULL,
  adults INT NOT NULL,
  children INT NOT NULL,
  room_type VARCHAR(255) NOT NULL,
  promotion VARCHAR(255) NOT NULL,
  inclusions TEXT NOT NULL,
  included TEXT NOT NULL,
  arrival DATE NOT NULL,
  departure DATE NOT NULL,
  booked_and_payable_by TEXT NOT NULL,
  remarks TEXT NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'Draft',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_vouchers_created_at (created_at),
  INDEX idx_vouchers_status (status)
);
